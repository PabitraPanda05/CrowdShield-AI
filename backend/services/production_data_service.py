
from __future__ import annotations

from pathlib import Path
from typing import Any

import json
import pandas as pd


# ================================================================
# CrowdShield AI — Production Data Service
# ================================================================

ROOT = Path(__file__).resolve().parents[2]

PRODUCTION_DIR = (
    ROOT
    / "data"
    / "processed"
    / "production_pipeline"
)


class ProductionDataService:
    """
    Read-only service for production AI pipeline artifacts.

    These files are generated by the validated production
    camera-driven AI pipeline.

    Risk scores are rule-based operational indices.
    They are NOT probabilities and are NOT validated injury/
    emergency predictions.
    """

    def __init__(self, production_dir: Path | None = None):

        self.production_dir = (
            Path(production_dir)
            if production_dir is not None
            else PRODUCTION_DIR
        )

    # ------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------

    def _csv(self, filename: str) -> pd.DataFrame:

        path = self.production_dir / filename

        if not path.exists():
            raise FileNotFoundError(
                f"Production data file not found: {path}"
            )

        return pd.read_csv(path)

    def _json(self, filename: str) -> dict[str, Any]:

        path = self.production_dir / filename

        if not path.exists():
            raise FileNotFoundError(
                f"Production JSON file not found: {path}"
            )

        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)

    # ------------------------------------------------------------
    # Production datasets
    # ------------------------------------------------------------

    def frame_risk_features(self) -> pd.DataFrame:

        return self._csv(
            "frame_risk_features.csv"
        )

    def temporal_windows(self) -> pd.DataFrame:

        return self._csv(
            "temporal_windows.csv"
        )

    def operational_risk(self) -> pd.DataFrame:

        return self._csv(
            "operational_risk.csv"
        )

    def response_decisions(self) -> pd.DataFrame:

        return self._csv(
            "response_decisions.csv"
        )

    def latest_state(self) -> dict[str, Any]:

        return self._json(
            "latest_state.json"
        )

    def metadata(self) -> dict[str, Any]:

        return self._json(
            "pipeline_metadata.json"
        )

    # ------------------------------------------------------------
    # Dashboard summary
    # ------------------------------------------------------------

    def dashboard_summary(self) -> dict[str, Any]:

        risk_df = self.operational_risk()

        # Read the DataFrame directly for aggregation.
        # response_decisions() intentionally returns API-ready
        # dictionaries, so it should not be used for DataFrame
        # aggregation here.
        response_df = self._csv(
            "response_decisions.csv"
        )

        latest = self.latest_state()

        return {
            "source": "production_pipeline",

            "processed_windows": int(
                len(risk_df)
            ),

            "minimum_risk_score": float(
                risk_df["operational_risk_score"].min()
            ),

            "mean_risk_score": float(
                risk_df["operational_risk_score"].mean()
            ),

            "maximum_risk_score": float(
                risk_df["operational_risk_score"].max()
            ),

            "risk_distribution": (
                risk_df["operational_risk_level"]
                .value_counts()
                .to_dict()
            ),

            "response_distribution": (
                response_df["response_action"]
                .value_counts()
                .to_dict()
            ),

            "latest_state": latest,

            "human_review_required": bool(
                latest.get(
                    "human_review_required",
                    True
                )
            ),

            "autonomous_emergency_action": bool(
                latest.get(
                    "autonomous_emergency_action",
                    False
                )
            ),
        }

    # ------------------------------------------------------------
    # Risk timeline
    # ------------------------------------------------------------

    def risk_timeline(self) -> list[dict[str, Any]]:

        df = self.operational_risk()

        columns = [
            "window_id",
            "start_time",
            "end_time",
            "operational_risk_score",
            "operational_risk_level",
            "dominant_risk_factor",
            "operational_risk_reason",
        ]

        available = [
            col for col in columns
            if col in df.columns
        ]

        return df[available].to_dict(
            orient="records"
        )

    # ------------------------------------------------------------
    # Alerts
    # ------------------------------------------------------------

    def alerts(self) -> list[dict[str, Any]]:

        risk_df = self.operational_risk()

        # Read the response CSV directly because
        # response_decisions() returns API-ready dictionaries.
        response_df = self._csv(
            "response_decisions.csv"
        )

        response_columns = [
            "window_id",
            "response_action",
            "response_priority",
            "response_reason",
            "active_signals",
            "human_review_required",
            "autonomous_emergency_action",
        ]

        available_columns = [
            column
            for column in response_columns
            if column in response_df.columns
        ]

        merged = risk_df.merge(
            response_df[available_columns],
            on="window_id",
            how="left",
            suffixes=("", "_response"),
        )

        # Production alert view:
        # HIGH / CRITICAL operational risk.
        #
        # These are rule-based operational alerts and are not
        # claims of confirmed emergencies.
        alert_df = merged[
            merged["operational_risk_level"].isin(
                ["HIGH", "CRITICAL"]
            )
        ]

        return alert_df.to_dict(
            orient="records"
        )

    # ------------------------------------------------------------
    # Crowd intelligence
    # ------------------------------------------------------------

    def crowd_intelligence(self) -> list[dict[str, Any]]:

        df = self.temporal_windows()

        columns = [
            "window_id",
            "start_time",
            "end_time",
            "average_people",
            "maximum_people",
            "minimum_people",
            "crowd_load",
            "movement_load",
            "spatial_load",
            "movement_event_count",
            "movement_event_ratio",
            "high_speed_signal",
            "mean_speed_px_per_sec",
            "maximum_speed_px_per_sec",
            "crowd_change",
            "crowd_growth_per_sec",
            "growth_load",
            "persistence",
        ]

        available = [
            col for col in columns
            if col in df.columns
        ]

        return df[available].to_dict(
            orient="records"
        )

    # ------------------------------------------------------------
    # Frame-level intelligence
    # ------------------------------------------------------------

    def frame_intelligence(self) -> list[dict[str, Any]]:

        df = self.frame_risk_features()

        return df.to_dict(
            orient="records"
        )

    # ------------------------------------------------------------
    # Production response decisions
    # ------------------------------------------------------------

    def response_decisions(self) -> list[dict[str, Any]]:

        df = self._csv(
            "response_decisions.csv"
        )

        return df.to_dict(
            orient="records"
        )


# Default service instance
production_data_service = ProductionDataService()
